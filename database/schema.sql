CREATE TABLE USUARIOS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROL VARCHAR2(20) DEFAULT 'USER' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_USUARIO_ROL CHECK (ROL IN ('USER', 'ADMIN'))
);

CREATE TABLE CATEGORIAS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(255)
);

CREATE TABLE TEMAS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TITULO VARCHAR2(200) NOT NULL,
    CONTENIDO CLOB NOT NULL,
    USUARIO_ID NUMBER NOT NULL,
    CATEGORIA_ID NUMBER NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_TEMA_USUARIO
        FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID),
    CONSTRAINT FK_TEMA_CATEGORIA
        FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS(ID)
);

CREATE TABLE COMENTARIOS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CONTENIDO CLOB NOT NULL,
    USUARIO_ID NUMBER NOT NULL,
    TEMA_ID NUMBER NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_COMENTARIO_USUARIO
        FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID),
    CONSTRAINT FK_COMENTARIO_TEMA
        FOREIGN KEY (TEMA_ID) REFERENCES TEMAS(ID)
);
